function chipFor(key, lang) {
  const p = PRESETS[key];
  if (!p) return null;
  let label;
  if (/^kb-\d+$/.test(key)) label = lang === 'hi' ? `${p.maxKB} KB से कम` : `Under ${p.maxKB} KB`;
  else label = (lang === 'hi' ? CHIP_LABELS_HI : CHIP_LABELS)[key] || p.name.replace(/\s*\(.*$/, '');
  return { key, label, sub: `${p.width} × ${p.height}` };
}

