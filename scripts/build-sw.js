#!/usr/bin/env node
/* Writes the list of the site's files and their content hashes into sw.js (between the precache markers).

   - STATIC_ASSETS lists every page, stylesheet, script, font and guide image of the site, found on
     disk, so a new page or script is never forgotten. It is the full offline copy, which a visitor
     downloads only when they ask for it on the Your data page; otherwise the service worker keeps
     just the pages this browser opens (see sw.js).
   - ASSET_HASHES holds a short hash of each file's content, in the same order. Files are cached under
     their path plus this hash, so a new release keeps the files that did not change and fetches only
     the ones that did.
   - SITE_BYTES and SITE_TRANSFER are the size of the full copy and about how much downloading it
     costs (gzip), shown on the Your data page.
   - Large libraries in js/vendor/ (pdf.js, pdf-lib) are cached on first use in VENDOR_CACHE, whose
     name changes only when a vendored file changes.
   - The Devanagari font is left out: no page shows Devanagari text, so it is fetched (and then
     cached) only if a visitor types some.
   `--check` exits 1 when sw.js is out of date. Called by scripts/sync-shell.js. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const zlib = require('node:zlib');

const root = path.resolve(__dirname, '..');
const SW = path.join(root, 'sw.js');
const ls = (dir, re) => fs.existsSync(path.join(root, dir)) ? fs.readdirSync(path.join(root, dir)).filter(f => re.test(f)).sort().map(f => `${dir}/${f}`.replace(/^\.\//, '')) : [];
const isStub = f => /<meta http-equiv="refresh"/i.test(fs.readFileSync(path.join(root, f), 'utf8'));

function walk(dir) {
  const out = [];
  for (const entry of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
    const rel = `${dir}/${entry.name}`;
    if (entry.isDirectory()) out.push(...walk(rel)); else out.push(rel);
  }
  return out.sort();
}

function assets() {
  const pages = [...ls('.', /\.html$/), ...ls('guides', /\.html$/)].filter(f => !isStub(f));
  return [
    ...pages,
    ...ls('css', /\.css$/), ...ls('css/vendor', /\.css$/), ...ls('css/webfonts', /\.woff2$/), ...ls('assets/fonts', /\.woff2$/).filter(f => !/devanagari/.test(f)),
    ...ls('js', /\.js$/), ...ls('js/lib', /\.js$/), ...ls('js/workers', /\.js$/), 'js/vendor/cropper.min.js',
    ...ls('favicon', /\.(png|ico|webmanifest)$/), ...ls('img/guides', /\.webp$/), ...ls('img/samples', /\.jpg$/)
  ];
}

function hashOf(files) {
  const h = crypto.createHash('sha256');
  for (const f of files) { h.update(f); h.update(fs.readFileSync(path.join(root, f))); }
  return h.digest('hex').slice(0, 10);
}
const fileHash = f => crypto.createHash('sha256').update(fs.readFileSync(path.join(root, f))).digest('hex').slice(0, 8);

function block() {
  const list = assets();
  const seen = new Set();
  const entries = list.map(f => ({ url: '/' + f.replace(/(^|\/)index\.html$/, '$1'), file: f }))
    .filter(e => !seen.has(e.url) && seen.add(e.url));
  const bytes = list.reduce((n, f) => n + fs.statSync(path.join(root, f)).size, 0);
  // Images and fonts are already compressed; text files travel gzipped.
  const transfer = list.reduce((n, f) => n + (/\.(html|css|js|webmanifest)$/.test(f) ? zlib.gzipSync(fs.readFileSync(path.join(root, f))).length : fs.statSync(path.join(root, f)).size), 0);
  const vendor = walk('js/vendor').filter(f => f !== 'js/vendor/cropper.min.js');
  return `/* precache:start (generated by scripts/build-sw.js; do not edit by hand) */
const VENDOR_CACHE = 'applyready-vendor-${hashOf(vendor)}';
const SITE_BYTES = ${bytes};
const SITE_TRANSFER = ${transfer};
const STATIC_ASSETS = [
${entries.map(e => `  '${e.url}'`).join(',\n')}
];
const ASSET_HASHES = '${entries.map(e => fileHash(e.file)).join(' ')}'.split(' ');
/* precache:end */`;
}

function run(check) {
  const sw = fs.readFileSync(SW, 'utf8');
  const re = /\/\* precache:start[\s\S]*?\/\* precache:end \*\//;
  if (!re.test(sw)) throw new Error('sw.js: missing precache markers');
  // The hash covers the pages, which do not change when only sw.js changes, so this converges.
  const next = sw.replace(re, block());
  if (next === sw) return false;
  if (!check) fs.writeFileSync(SW, next);
  return true;
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  const changed = run(check);
  if (check && changed) { console.error('sw.js is out of date: run node scripts/sync-shell.js'); process.exit(1); }
  console.log(changed ? 'sw.js precache written' : 'sw.js precache up to date');
}
module.exports = { run, assets };
