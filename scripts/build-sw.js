#!/usr/bin/env node
/* Writes the precache list and cache names into sw.js (between the precache markers).

   - STATIC_ASSETS lists every page, stylesheet, script, font and guide image the site needs offline,
     found on disk, so a new page or script is never forgotten.
   - CACHE_NAME is a hash of the content of those files: any change to any of them gives returning
     visitors a fresh cache on their next visit, with no manual version bump.
   - Large libraries in js/vendor/ (pdf.js, pdf-lib) are not precached for everyone. They are cached
     on first use in VENDOR_CACHE, whose name changes only when a vendored file changes.
   `--check` exits 1 when sw.js is out of date. Called by scripts/sync-shell.js. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '..');
const SW = path.join(root, 'sw.js');
const ls = (dir, re) => fs.existsSync(path.join(root, dir)) ? fs.readdirSync(path.join(root, dir)).filter(f => re.test(f)).sort().map(f => `${dir}/${f}`.replace(/^\.\//, '')) : [];
const isStub = f => /<meta http-equiv="refresh"/i.test(fs.readFileSync(path.join(root, f), 'utf8'));

function walk(dir) {
  const out = [];
  for (const entry of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
    const rel = `${dir}/${entry.name}`;
    if (entry.isDirectory()) out.push(...walk(rel)); else out.push(rel);
  }
  return out.sort();
}

function assets() {
  const pages = [...ls('.', /\.html$/), ...ls('guides', /\.html$/)].filter(f => !isStub(f));
  return [
    ...pages,
    ...ls('css', /\.css$/), ...ls('css/vendor', /\.css$/), ...ls('css/webfonts', /\.woff2$/), ...ls('assets/fonts', /\.woff2$/),
    ...ls('js', /\.js$/), ...ls('js/lib', /\.js$/), ...ls('js/workers', /\.js$/), 'js/vendor/cropper.min.js',
    ...ls('favicon', /\.(png|ico|webmanifest)$/), ...ls('img/guides', /\.webp$/), ...ls('img/samples', /\.jpg$/)
  ];
}

function hashOf(files) {
  const h = crypto.createHash('sha256');
  for (const f of files) { h.update(f); h.update(fs.readFileSync(path.join(root, f))); }
  return h.digest('hex').slice(0, 10);
}

function block() {
  const list = assets();
  const urls = ['/', ...list.map(f => '/' + f.replace(/(^|\/)index\.html$/, '$1'))].filter((u, i, all) => all.indexOf(u) === i);
  const vendor = walk('js/vendor').filter(f => f !== 'js/vendor/cropper.min.js');
  return `/* precache:start (generated by scripts/build-sw.js; do not edit by hand) */
const CACHE_NAME = 'applyready-${hashOf(list)}';
const VENDOR_CACHE = 'applyready-vendor-${hashOf(vendor)}';
const STATIC_ASSETS = [
${urls.map(u => `  '${u}'`).join(',\n')}
];
/* precache:end */`;
}

function run(check) {
  const sw = fs.readFileSync(SW, 'utf8');
  const re = /\/\* precache:start[\s\S]*?\/\* precache:end \*\//;
  if (!re.test(sw)) throw new Error('sw.js: missing precache markers');
  // The hash covers the pages, which do not change when only sw.js changes, so this converges.
  const next = sw.replace(re, block());
  if (next === sw) return false;
  if (!check) fs.writeFileSync(SW, next);
  return true;
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  const changed = run(check);
  if (check && changed) { console.error('sw.js is out of date: run node scripts/sync-shell.js'); process.exit(1); }
  console.log(changed ? 'sw.js precache written' : 'sw.js precache up to date');
}
module.exports = { run, assets };
