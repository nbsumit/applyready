#!/usr/bin/env node
/* Writes js/tool-index.js: the data behind site search, the tool directory and "recently used".
   Generated from scripts/lib/tools.js and the guide pages; do not edit the output by hand.
   `--check` exits 1 if the committed file is out of date. Called by scripts/sync-shell.js. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { CATEGORIES, PAGES, liveTools } = require('./lib/tools');

const root = path.resolve(__dirname, '..');
const OUT = path.join(root, 'js', 'tool-index.js');

const decode = s => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&rsquo;/g, '’');
const strip = s => decode(s.replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim();

function guides() {
  const dir = path.join(root, 'guides');
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter(f => f.endsWith('.html') && f !== 'index.html').sort().map(f => {
    const html = fs.readFileSync(path.join(dir, f), 'utf8');
    if (/<meta name="robots" content="noindex/.test(html) || /http-equiv="refresh"/.test(html)) return null;
    const h1 = (html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [])[1];
    const desc = (html.match(/<meta name="description" content="([^"]*)"/) || [])[1] || '';
    if (!h1) return null;
    return { id: 'guide:' + f.replace(/\.html$/, ''), kind: 'guide', name: strip(h1), path: 'guides/' + f, icon: 'book-open', summary: strip(desc).slice(0, 140), keywords: [] };
  }).filter(Boolean);
}

function build() {
  const catName = Object.fromEntries(CATEGORIES.map(c => [c.id, c.name]));
  const tools = liveTools().map(t => ({
    id: t.id, kind: 'tool', name: t.name, path: t.path, icon: t.icon, category: t.category,
    categoryName: catName[t.category], also: t.also || [], summary: t.summary, keywords: t.keywords || [],
    directory: t.directory !== false, popular: t.popular || 0
  }));
  const pages = PAGES.filter(p => fs.existsSync(path.join(root, p.path.endsWith('/') ? p.path + 'index.html' : p.path)))
    .map(p => ({ id: 'page:' + p.id, kind: 'page', name: p.name, path: p.path, icon: p.icon, summary: p.summary, keywords: p.keywords }));
  const data = { categories: CATEGORIES, items: [...tools, ...pages, ...guides()] };
  return `/* Generated by scripts/build-tool-index.js from scripts/lib/tools.js. Do not edit. */\nwindow.APPLYREADY_TOOL_INDEX = ${JSON.stringify(data)};\n`;
}

function run(check) {
  const next = build();
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (next === current) return false;
  if (!check) fs.writeFileSync(OUT, next);
  return true;
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  const changed = run(check);
  if (check && changed) { console.error('js/tool-index.js is out of date: run node scripts/sync-shell.js'); process.exit(1); }
  console.log(changed ? 'js/tool-index.js written' : 'js/tool-index.js up to date');
}

module.exports = { run, build };
