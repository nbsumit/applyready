/* ApplyReady service worker: offline support, without downloading the whole site uninvited.

   What it keeps, in the cache CACHE_NAME:
   - /offline.html and the few files it needs that a page may not have loaded (OFFLINE_SHELL: its
     script and the two icon fonts), fetched when the service worker is installed (about 35 KB).
     The offline page is shown for a page that was never opened while online, and lists the pages
     that are kept.
   - The pages and files this browser opens, as they are fetched. The first page loads before the
     service worker starts, so js/site.js sends the list of what it loaded and the service worker
     copies those files from the browser's own HTTP cache, without downloading them again.
   - The whole site (STATIC_ASSETS, with the PDF libraries in VENDOR_ASSETS), only when the visitor
     asks for it on the Your data page.
   Vendored libraries (pdf.js, pdf-lib) go to VENDOR_CACHE, the first time a PDF tool uses them or
   when the whole site is saved.

   Pages: network first, so a visitor always gets the current page when online; the cached copy is
   used offline, and /offline.html when a page was never cached.
   Assets: served from the cache and refreshed in the background (stale-while-revalidate).

   Each file is stored once, under its path and the hash of its content in this release
   (/js/site.js?sw=1a2b3c4d), whatever query string the page used. A new release keeps the files
   that did not change, fetches again the changed files this browser had kept (not when Save-Data is
   on), and drops the old copies when it takes over.

   Only same-origin GET requests are handled. Nothing a visitor types or opens is cached: tools
   read files with the File API, which never goes through the network. */

