const CACHE_NAME = 'applyready-files';
const HASH_OF = new Map(STATIC_ASSETS.map((url, i) => [url, ASSET_HASHES[i]]));

// The visitor asked their browser to use less data (Save-Data).
function saveData() {
  try { return !!(self.navigator.connection && self.navigator.connection.saveData); } catch (e) { return false; }
}

// /guides/index.html and /guides/ are the same page.
function pathOf(url) {
  const p = url.pathname;
  return p.endsWith('/index.html') ? p.slice(0, -'index.html'.length) : p;
}

// The key a file is stored under: its path, with the content hash for files of this release.
function keyFor(url) {
  const p = pathOf(url);
  const hash = HASH_OF.get(p);
  return new URL(hash ? `${p}?sw=${hash}` : p, self.location.origin).href;
}

function isVendor(url) {
  return url.pathname.startsWith('/js/vendor/') && !url.pathname.endsWith('cropper.min.js');
}
function cacheFor(url) { return isVendor(url) ? VENDOR_CACHE : CACHE_NAME; }

function matchCached(url) {
  return caches.open(cacheFor(url)).then(cache => cache.match(keyFor(url))).catch(() => undefined);
}

function storable(response) {
  return !!response && response.status === 200 && response.type === 'basic' && !response.redirected;
}

function store(url, response) {
  if (!storable(response)) return Promise.resolve();
  const copy = response.clone();
  return caches.open(cacheFor(url)).then(cache => cache.put(keyFor(url), copy)).catch(() => {});
}

// Fetch one file of the site into the cache. mode is a fetch cache mode: 'no-cache' asks the server
// whether the browser's copy is current (a few hundred bytes when it is), 'force-cache' takes the
// browser's copy when it has one.
async function fetchInto(href, mode) {
  const url = new URL(href, self.location.origin);
  if (url.origin !== self.location.origin) return false;
  const response = await fetch(url.href, { cache: mode, credentials: 'same-origin' });
  if (!storable(response)) return false;
  await (await caches.open(cacheFor(url))).put(keyFor(url), response);
  return true;
}

// Run fn on every item, four at a time. A failure of one item does not stop the others.
async function inParallel(items, fn, onEach) {
  let next = 0, done = 0;
  const worker = async () => {
    while (next < items.length) {
      const item = items[next++];
      try { await fn(item); } catch (e) { /* fn reports its own result */ }
      done++;
      if (onEach) onEach(done);
    }
  };
  await Promise.all(Array.from({ length: Math.min(4, items.length) }, worker));
}

async function cachedKeys(name) {
  try { return new Set((await (await caches.open(name || CACHE_NAME)).keys()).map(r => r.url)); } catch (e) { return new Set(); }
}

// Files of the site that this browser kept from an earlier release but that changed since: fetch
// them again now, so what worked offline keeps working. Unchanged files are already under the right key.
// The same for the PDF libraries: a release that changes one renames VENDOR_CACHE, so the ones kept
// under the old name are fetched again into the new one.
async function refreshKept() {
  if (saveData()) return;
  const have = await cachedKeys();
  const haveVendor = await cachedKeys(VENDOR_CACHE);
  const changed = new Set();
  for (const name of await caches.keys()) {
    if (name === VENDOR_CACHE) continue;
    const vendorCache = name.startsWith('applyready-vendor-');
    const cache = await caches.open(name);
    for (const request of await cache.keys()) {
      const url = new URL(request.url);
      if (url.origin !== self.location.origin) continue;
      if (vendorCache) { if (isVendor(url) && !haveVendor.has(keyFor(url))) changed.add(pathOf(url)); continue; }
      if (!HASH_OF.has(pathOf(url))) continue;
      if (!have.has(keyFor(url))) changed.add(pathOf(url));
    }
  }
  await inParallel([...changed], p => fetchInto(p, 'no-cache'));
}

const OFFLINE_PAGE = new URL('/offline.html', self.location.origin);
// The offline page's script and icon fonts. Without them it would show blank icons and could not
// list the pages that are kept. Optional: the offline page still works without them.
async function keepOfflineShell() {
  const have = await cachedKeys();
  const todo = OFFLINE_SHELL.filter(p => !have.has(keyFor(new URL(p, self.location.origin))));
  await inParallel(todo, p => fetchInto(p, 'no-cache').catch(() => false));
}
// The offline page goes when the visitor removes the offline copy on Your data; fetch it again then.
async function keepOfflinePage() {
  if (!(await matchCached(OFFLINE_PAGE))) await fetchInto(OFFLINE_PAGE.href, 'no-cache').catch(() => false);
  await keepOfflineShell();
}

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    if (!(await fetchInto(OFFLINE_PAGE.href, 'no-cache'))) throw new Error('offline.html could not be cached');
    await keepOfflineShell();
    await refreshKept();
    await self.skipWaiting();
  })());
});

// Old caches, and copies of files from earlier releases, are removed once this version takes over.
async function prune() {
  for (const name of await caches.keys()) {
    if (name !== CACHE_NAME && name !== VENDOR_CACHE) await caches.delete(name);
  }
  const cache = await caches.open(CACHE_NAME);
  for (const request of await cache.keys()) {
    const url = new URL(request.url);
    if (url.search && request.url !== keyFor(url)) await cache.delete(request);
  }
}

self.addEventListener('activate', event => {
  event.waitUntil(prune().catch(() => {}).then(() => self.clients.claim()));
});

/* Messages from the site's own pages:
   { type: 'cache-page', urls }  the first page, with the files it loaded before the service worker
                                 started; copied from the browser's HTTP cache.
   { type: 'site-info' } + port  replies { files, saved, bytes, transfer } about the full copy (the
                                 site's files and the PDF libraries).
   { type: 'save-site' } + port  saves every file of the site, replying { type: 'progress', done,
                                 total } as it goes and { type: 'done', saved, files, failed } at the end. */
function siteFile(href) {
  try {
    const url = new URL(href, self.location.origin);
    return url.origin === self.location.origin && (HASH_OF.has(pathOf(url)) || isVendor(url)) ? url : null;
  } catch (e) { return null; }
}

async function cachePage(urls) {
  if (!Array.isArray(urls)) return;
  const have = await cachedKeys();
  const todo = urls.slice(0, 300).map(u => (typeof u === 'string' ? siteFile(u) : null))
    .filter(url => url && (isVendor(url) || !have.has(keyFor(url))));
  await inParallel(todo, url => fetchInto(url.href, 'force-cache'));
}

// Every file of the full copy that this browser does not keep yet.
async function missingFiles() {
  const have = await cachedKeys();
  const haveVendor = await cachedKeys(VENDOR_CACHE);
  const kept = p => { const url = new URL(p, self.location.origin); return (isVendor(url) ? haveVendor : have).has(keyFor(url)); };
  return STATIC_ASSETS.concat(VENDOR_ASSETS).filter(p => !kept(p));
}

async function siteInfo() {
  const files = STATIC_ASSETS.length + VENDOR_ASSETS.length;
  const saved = files - (await missingFiles()).length;
  return { type: 'info', files, saved, bytes: SITE_BYTES, transfer: SITE_TRANSFER };
}

async function saveSite(port) {
  const todo = await missingFiles();
  let failed = 0;
  await inParallel(todo, async p => { if (!(await fetchInto(p, 'no-cache'))) failed++; }, done => {
    if (done % 5 === 0 || done === todo.length) port.postMessage({ type: 'progress', done, total: todo.length });
  });
  const info = await siteInfo();
  port.postMessage({ type: 'done', saved: info.saved, files: info.files, failed: info.files - info.saved });
}

self.addEventListener('message', event => {
  if (event.origin && event.origin !== self.location.origin) return;
  const data = event.data || {};
  const port = event.ports && event.ports[0];
  if (data.type === 'cache-page') event.waitUntil(cachePage(data.urls).catch(() => {}));
  else if (data.type === 'site-info' && port) event.waitUntil(siteInfo().then(info => port.postMessage(info)));
  else if (data.type === 'save-site' && port) event.waitUntil(saveSite(port).catch(() => port.postMessage({ type: 'done', failed: -1 })));
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  const accept = request.headers.get('accept') || '';
  if (request.mode === 'navigate' || accept.includes('text/html')) {
    event.respondWith(
      fetch(request)
        .then(response => { event.waitUntil(store(url, response).then(keepOfflinePage)); return response; })
        .catch(() => matchCached(url).then(cached => cached || matchCached(OFFLINE_PAGE)).then(cached => cached || Response.error()))
    );
    return;
  }

  event.respondWith(
    matchCached(url).then(cached => {
      const network = fetch(request)
        .then(response => { event.waitUntil(store(url, response)); return response; })
        .catch(() => null);
      if (cached) { event.waitUntil(network); return cached; }
      return network.then(response => response || Response.error());
    })
  );
});
